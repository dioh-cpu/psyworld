-- Idle-only, server-computed hunt rewards and capture assets.
-- The API authenticates the Supabase user and invokes this service-role-only RPC.
create table public.idle_hunt_maps (
  map_key text primary key,
  region text not null,
  species_id integer not null check (species_id between 1 and 1025),
  species_name text not null,
  min_trainer_level integer not null check (min_trainer_level between 1 and 10000),
  enemy_level integer not null check (enemy_level between 1 and 10000),
  tier text not null check (tier in ('E','D','C','B','A','S','SS','SSS','UR','UR+','UR++')),
  min_quality text not null,
  max_quality text not null
);

create table public.idle_hunt_profiles (
  user_id uuid primary key references public.idle_accounts(user_id) on delete cascade,
  trainer_level integer not null default 1 check (trainer_level between 1 and 10000),
  trainer_xp bigint not null default 0 check (trainer_xp >= 0),
  total_kills bigint not null default 0 check (total_kills >= 0),
  total_captures bigint not null default 0 check (total_captures >= 0),
  last_victory_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.idle_hunt_tickets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.idle_hunt_profiles(user_id) on delete cascade,
  map_key text not null references public.idle_hunt_maps(map_key),
  species_id integer not null,
  species_name text not null,
  enemy_level integer not null,
  tier text not null,
  rarity_name text not null,
  rarity_mult numeric not null check (rarity_mult > 0),
  rarity_index integer not null check (rarity_index between 0 and 10),
  min_duration_seconds numeric not null check (min_duration_seconds >= 2),
  status text not null default 'started' check (status in ('started','won','expired')),
  issued_at timestamptz not null default clock_timestamp(),
  expires_at timestamptz not null,
  victory_at timestamptz,
  capture_attempted boolean not null default false,
  captured boolean,
  victory_result jsonb,
  capture_result jsonb
);
create index idle_hunt_tickets_owner on public.idle_hunt_tickets(user_id,status,expires_at);

create table public.idle_hunt_receipts (
  user_id uuid not null references public.idle_hunt_profiles(user_id) on delete cascade,
  request_id uuid not null,
  action text not null,
  payload jsonb not null,
  result jsonb not null,
  created_at timestamptz not null default now(),
  primary key(user_id,request_id)
);

create table public.idle_hunt_qualities (
  quality_index integer primary key check (quality_index between 0 and 10),
  name text not null unique,
  multiplier numeric not null check (multiplier > 0),
  weight numeric not null check (weight >= 0)
);

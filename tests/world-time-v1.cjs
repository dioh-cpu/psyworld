const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const sandbox={window:{},Intl,Date,Math,Number,String,Set,Array};
vm.runInNewContext(fs.readFileSync('core/world-time-v1.js','utf8'),sandbox,{filename:'core/world-time-v1.js'});
const clock=sandbox.window.PsyWorldTimeV1;
const at=utc=>Date.parse('2026-11-07T'+utc+'Z');
const dawn=clock.getState(at('08:00')),day=clock.getState(at('12:00')),dusk=clock.getState(at('21:00')),night=clock.getState(at('00:00'));
assert.equal(dawn.clockText,'05:00');assert.equal(dawn.phase,'dawn');
assert.equal(day.clockText,'09:00');assert.equal(day.phase,'day');assert.equal(day.darkness,0);
assert.equal(dusk.clockText,'18:00');assert.equal(dusk.phase,'dusk');assert.ok(dusk.warmth>0&&dusk.darkness>0);
assert.equal(night.clockText,'21:00');assert.equal(night.phase,'night');assert.equal(night.isNight,true);
assert.equal(clock.timezone,'America/Sao_Paulo');
const roster=[16,19,21,52,84,108],dayPool=clock.weightSpecies(roster,'route-1',at('12:00')),nightPool=clock.weightSpecies(roster,'route-1',at('00:00'));
assert.deepEqual([...new Set(dayPool)],roster);assert.deepEqual([...new Set(nightPool)],roster);
assert.equal(dayPool.filter(id=>id===16).length,2);assert.equal(dayPool.filter(id=>id===19).length,1);
assert.equal(nightPool.filter(id=>id===19).length,2);assert.equal(nightPool.filter(id=>id===52).length,2);
const records=clock.weightEncounterRecords(roster.map(id=>({id,name:'Species '+id})), 'route-1',at('00:00'));
assert.equal(records.length,nightPool.length);assert.ok(records.every(record=>record.name==='Species '+record.id));
const drawn=[];const ctx={globalCompositeOperation:'source-over',globalAlpha:1,fillStyle:'',save(){},restore(){},setTransform(){},fillRect(x,y,w,h){drawn.push({color:this.fillStyle,alpha:this.globalAlpha,mode:this.globalCompositeOperation})}};
clock.drawAmbient(ctx,320,180,at('12:00'));assert.equal(drawn.length,0);
clock.drawAmbient(ctx,320,180,at('00:00'));assert.equal(drawn.length,1);assert.equal(drawn[0].mode,'multiply');
clock.drawAmbient(ctx,320,180,at('21:00'));assert.equal(drawn.length,3);assert.equal(drawn[2].mode,'screen');
let label={textContent:'',title:'',dataset:{},attrs:{},setAttribute(k,v){this.attrs[k]=v}};
clock.updateBadge(label,at('00:00'));assert.equal(label.textContent,'☾ 21:00');assert.match(label.attrs['aria-label'],/Brasília/);
assert.deepEqual({phases:[dawn.phase,day.phase,dusk.phase,night.phase],dayPool:dayPool.length,nightPool:nightPool.length,ambientDraws:drawn.length},{phases:['dawn','day','dusk','night'],dayPool:9,nightPool:8,ambientDraws:3});

const auraSandbox={window:{performance:{now:()=>1250},matchMedia:()=>({matches:false})}};
vm.runInNewContext(fs.readFileSync('core/costume-aura-v1.js','utf8'),auraSandbox,{filename:'core/costume-aura-v1.js'});
const aura=auraSandbox.window.PsyCostumeAuraV1,marks=[];
const auraCtx={globalCompositeOperation:'source-over',globalAlpha:1,fillStyle:'',strokeStyle:'',lineWidth:1,save(){},restore(){},beginPath(){},ellipse(...p){marks.push(['ellipse',...p])},fill(){marks.push(['fill'])},stroke(){marks.push(['stroke'])},fillRect(...p){marks.push(['pixel',...p])}};
assert.equal(aura.palette('basic-adventure-boy.webp'),null);
assert.deepEqual([...aura.palette('divine-adventure-boy.webp')],['#ffe59a','#fff2c4']);
assert.deepEqual([...aura.palette('horror-jason-adventure-boy.webp')],['#f18a74','#ffcf8b']);
assert.equal(aura.draw(auraCtx,'basic-adventure-boy.webp',20,50),false);
assert.equal(aura.draw(auraCtx,'apex-adventure-boy.webp',20,50),true);
assert.equal(marks.filter(x=>x[0]==='ellipse').length,2);assert.equal(marks.filter(x=>x[0]==='pixel').length,2);
console.log('PASS: Brasília-time day/dawn/dusk/night, reversible ambient grading, time-weighted existing encounters, badge copy, and costume-only pixel auras');

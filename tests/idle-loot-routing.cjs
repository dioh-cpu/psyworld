const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
(async()=>{
await import('../core/battle-loot-rules-v1.js');
const lootRules=globalThis.PsyBattleLootRulesV1;
assert(lootRules,'shared battle loot rules import in the test runtime');
const source=fs.readFileSync(require('node:path').join(__dirname,'../core/shared-mode-drops-v1.js'),'utf8');
const mainProfile={inventory:{},meta:{}};
const idleProfile={meta:{modeEconomies:{psyIdle:{gold:0,drops:{'idle:item:Essence%20Of%20Fire':2},packs:{}}}}};
const fixedMath=Object.create(Math);fixedMath.random=()=>0;
const window={P:mainProfile,__psyIdleProfile:idleProfile,PSY:{},RARITIES:[],PsyBattleLootRulesV1:lootRules,TYPE_BY_ID_FULL:{1:['Fire'],16:'Normal/Voador',19:'Normal'},autoSave(){},updateHUD(){},notif(){},psyQueueIdleSave(){},getTotalBuff(){return 0}};
vm.runInNewContext(source,{window,P:mainProfile,Math:fixedMath,console,Map,WeakSet,Number,String,Array,Object,JSON,Date,decodeURIComponent,encodeURIComponent});
assert.equal(window.psyModeEconomy('idle').currencyId,'idle:gold','Idle wallet keeps its currency identity');
assert.equal(window.psyModeEconomy('idle').drops['Essence Of Fire'],2,'legacy encoded Idle loot is normalized');
window.psySharedCombatDrop({id:1,type:'Fire'},'idle');
const idleDrops=idleProfile.meta.modeEconomies.psyIdle.drops;
assert.ok(Number(idleDrops['Essence Of Fire'])>2,'combat drops go into the Idle profile Bag');
assert.ok(Number(idleDrops['Fire Tail'])>0,'quest materials go into the Idle profile Bag');
assert.deepEqual(mainProfile.meta,{},'Idle combat does not contaminate the World profile');
const level1=window.PSY.sharedModeDrops.dropTableForId({id:1,level:1},'idle');
const level10=window.PSY.sharedModeDrops.dropTableForId({id:1,level:10},'idle');
const level100=window.PSY.sharedModeDrops.dropTableForId({id:1,level:100},'idle');
assert.equal(level1.entries[0].chance,.03,'Lv.1 keeps the established 3% craft-essence base rate');
assert.ok(Math.abs(level10.entries[0].chance-.03*1.108)<1e-12,'Lv.10 improves Idle loot odds by the level curve');
assert.equal(level100.entries[0].chance,.06,'Lv.100 is capped at 2x the Lv.1 Idle chance');
assert.notEqual(level1,level100,'drop profiles are cached separately by enemy level');
assert.equal(window.PsyTypeStoneDropsV1.forEnemy({id:16,type:'Normal/Flying'}),'Flying Stone','Pidgey receives the stone for its non-Normal Flying type');
assert.equal(window.PsyTypeStoneDropsV1.forEnemy({id:19,type:'Normal'}),'Heart Stone','Rattata keeps its matching Heart Stone');
assert.equal(window.PsyTypeStoneDropsV1.forEnemy({id:16,type:'Normal/Flying'}),'Flying Stone','secondary Flying is preferred over Normal');
const originalRandom=fixedMath.random;fixedMath.random=()=>0;
const battleDrop=window.psySharedCombatDrop({id:16,type:'Normal'},'wild');
fixedMath.random=originalRandom;
assert(mainProfile.inventory.Straw>=1,'Pidgey receives the Flying common material even when its object type is abbreviated');
assert(mainProfile.inventory.Feather>=1,'Pidgey receives the Flying uncommon material');
assert(mainProfile.inventory['Flying Stone']>=1,'Pidgey receives only the matching Flying Stone');
assert.equal(mainProfile.inventory['Heart Stone']||0,0,'Pidgey never receives the Normal Heart Stone');
assert.equal(mainProfile.inventory['Bug Stone']||0,0,'Pidgey never receives an unrelated Bug Stone');
assert(battleDrop.includes('Straw ×1'),'the shared combat drop report includes guaranteed common quantity');
const before=mainProfile.inventory['Flying Stone'];window.psySharedWorldRareDrop({id:16,level:2,type:'Normal/Flying'});
assert.equal(mainProfile.inventory['Flying Stone'],before,'World rare loot cannot add a second matching stone roll');
console.log('Idle loot routing and typed stone drops: ok');
})().catch(error=>{console.error(error);process.exitCode=1});

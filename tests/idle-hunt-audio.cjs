const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');

const source = fs.readFileSync(path.join(__dirname, '..', 'modes/idle-realistic-v1.js'), 'utf8');
const start = source.indexOf('const IDLE_HUNT_SFX_GAPS=');
const end = source.indexOf('function addIdlePlayerXp(', start);
assert.ok(start >= 0 && end > start, 'Idle hunt audio limiter exists');
let now = 0;
const played = [];
const audio = { typeKey: type => type.toLowerCase(), sfx: (name, options) => played.push({ name, options }) };
const context = { W: { psyAudio: audio }, performance: { now: () => now }, Map, Number, String };
vm.runInNewContext(source.slice(start, end), context);
assert.equal(context.idleHuntMoveSfx({ type: 'Fire' }), true);
assert.equal(context.idleHuntMoveSfx({ type: 'Water' }), false, 'different attack elements share the same cooldown');
now = 759;
assert.equal(context.idleHuntMoveSfx({ type: 'Grass' }), false, 'rapid repeated moves are suppressed');
now = 760;
assert.equal(context.idleHuntMoveSfx({ type: 'Water' }), true, 'one quiet move effect returns after the limiter interval');
assert.equal(played.length, 2);
assert.equal(played[0].options.volume, 0.22, 'hunt attack effects use reduced volume');
now = 1000;
assert.equal(context.idleHuntSfx('rare_drop', { channel: 'rare-drop', volume: 0.34, cooldown: 2400 }), true);
assert.equal(context.idleHuntSfx('rare_drop', { channel: 'rare-drop', volume: 0.34, cooldown: 2400 }), false, 'repeated rare-drop effects are suppressed');
assert.equal(played.length, 3);
assert.match(source, /function recordIdleDrop\(name\)\{if\(!name\)return;if\(\/stone\|candy\|pack\|core\/i\.test\(name\)\)idleHuntSfx\('rare_drop'/, 'ordinary hunt loot has no repeated sound');
assert.match(source, /captureFeedback\([^)]*\)\{[^}]*idleHuntSfx\(success\?'capture':'capture_fail'/, 'capture outcome audio is preserved');
assert.match(source, /idleHuntSfx\('shiny_found'/, 'the shiny encounter cue is preserved');
console.log('PASS: Idle hunt limits repeated attack and rare-drop sounds, lowers volume, and keeps capture/Shiny cues');

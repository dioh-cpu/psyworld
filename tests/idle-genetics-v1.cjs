const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../core/idle-genetics-v1.js'),'utf8');
const window={};
vm.runInNewContext(source,{window,Math,Number,String,Array,Object});
const genetics=window.PsyIdleGenetics;
assert.ok(genetics,'Idle genetics helper loads');
const newPokemon={id:25};
const first=genetics.ensure(newPokemon,()=>0.5);
assert.deepEqual(JSON.parse(JSON.stringify(Object.keys(first.ivs).sort())),['atk','def','hp','spd']);
assert.deepEqual(Object.values(first.ivs),[16,16,16,16]);
assert.ok(genetics.natures.some(n=>n.name===first.nature.name));
const stable=JSON.stringify(first);
genetics.ensure(newPokemon,()=>0);
assert.equal(JSON.stringify(genetics.ensure(newPokemon)),stable,'existing IVs and Nature stay stable after reload');
const low={ivs:{hp:0,atk:0,def:0,spd:0},nature:{name:'Firme'}};
const high={ivs:{hp:32,atk:31,def:22,spd:17},nature:{name:'Neutra'}};
assert.ok(genetics.multiplier(high,'hp')>genetics.multiplier(low,'hp'));
assert.ok(genetics.multiplier(high,'atk')>1);
assert.ok(genetics.multiplier(low,'hp')<1);
const quasiBest={ivs:{hp:32,atk:32,def:32,spd:32},nature:{name:'Firme',up:'atk',down:'spd'}};
const niceWorst={ivs:{hp:0,atk:0,def:0,spd:0},nature:{name:'Robusta',up:'def',down:'atk'}};
assert.ok(1.1*genetics.multiplier(quasiBest,'atk')<1.2*genetics.multiplier(niceWorst,'atk'),'Nice must stay stronger than Quase Lixo at equal species/level/forms even against best-vs-worst IV/Nature');
assert.ok(genetics.multiplier(high,'atk')-genetics.multiplier(low,'atk')<.07,'IV and Nature are a small bonus beneath the minimum quality step');
const rarityNames=['Lixo','Quase Lixo','Nice','Belezura','Lêndea','Bombado','Pika das Galáxias'];
const rarities=rarityNames.map((n,i)=>({n,mult:1+i*.1}));
const child=genetics.breed(low,high,rarities,()=>0,4);
for(const stat of genetics.stats)assert.ok(child.ivs[stat]>=Math.max(low.ivs[stat],high.ivs[stat]),stat+' IV inheritance');
assert.equal(child.rarity.n,'Bombado','breeding advances exactly one quality step at 25% roll');
const noAdvance=genetics.breed(low,high,rarities,()=>0.99,4);
assert.equal(noAdvance.rarity.n,'Lêndea','breeding keeps the Lêndea floor when no upgrade rolls');
console.log('Idle genetics rules: ok');

/* node tests/halloween-status-inventory-v1.cjs */
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const season=fs.readFileSync('core/seasonal-event-v1.js','utf8');
const titles=fs.readFileSync('core/titles-progression-v2.js','utf8');
const bag=fs.readFileSync('core/legacy-runtime.js','utf8');
const city=fs.readFileSync('core/city-halloween.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const player={inventory:{'Doce de Halloween':1000},meta:{},team:[{id:912}]};
const W={P:player,notif:()=>{},setTimeout:()=>0,autoSave:()=>{},getTotalBuff:()=>0};
const D={readyState:'loading',addEventListener:()=>{},getElementById:()=>null,createElement:()=>({style:{}})};
vm.runInNewContext(titles,{window:W,document:D,P:player});
vm.runInNewContext(season,{window:W,document:D,P:player});
const S=W.PsySeason,T=W.PsyTitles;
assert(S.buy('incense'));
assert.equal(player.inventory['Doce de Halloween'],700);
assert.equal(player.inventory['Incenso de Halloween'],1);
assert.equal(S.incenseStatus().charges.length,0,'Buy must not activate incense');
const before=Date.now();
assert(S.useIncense());
assert.equal(player.inventory['Incenso de Halloween'],0);
assert.equal(S.incenseStatus().charges.length,1);
assert(Math.abs(S.incenseStatus().spawnPct-2)<1e-8,'One charge adds 1pp');
assert(S.incenseStatus().nextExpiry>=before+3600000-1000,'One-hour duration');
assert(S.incenseStatus().nextExpiry<=Date.now()+3600000+1000);
assert(T.acquire('kills:1',true));
assert.equal(T.bonus('xp'),.4);
assert(T.equip(''));
assert.equal(T.bonus('xp'),.4,'Hiding a title must not clear bonuses');
assert(S.titleBonusRows().some(x=>x.name==='XP'&&x.value===.4));
assert(bag.includes('window.psyShowBagItemDetails=function(name)'),'Real item detail panel');
assert(bag.includes("if(name==='Incenso de Halloween'){const used="),'Refresh after incense');
assert(bag.includes("window.psyBagFilter==='other'?!['ball','potion','stone','craft','quest','special']"),'Exclude specials from Others');
assert(bag.includes("const itemCategory=name=>isSpecial(name)?'special':baseCategory(name)"),'Event item classifier');
assert(html.includes("psySetBagFilter('special',this)"),'Specials tab');
assert(html.includes('HALLOWEEN_TITLE_SHIMMER_V2_20261107'),'Fresh seasonal script');
assert(city.includes('drawTitle(c,w/2,h/2-83)'),'Trainer-relative title');
assert(!city.includes('drawTitle(c,center.x,center.y-95)'),'No plaza-anchored title');
assert(season.includes('W.setInterval?.(refresh,1000)'),'Visible timer must update');
console.log('PASS: buy/use incense, one-hour effect, title bonus persistence, Specials, item details, title position and timer');
